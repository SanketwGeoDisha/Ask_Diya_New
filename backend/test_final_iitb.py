    print(f"2. Pattern is generated by collector: {'✓ YES' if pattern_found else '✗ NO'}")
    
    if pdf_accessible and pattern_found:
        print(f"\n✓✓✓ COMPLETE SUCCESS!")
        print(f"The NIRF collector WILL NOW find the IIT Bombay 2025 PDF")
